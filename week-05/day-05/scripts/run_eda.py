import pandas as pd
import matplotlib.pyplot as plt
from pathlib import Path
import sweetviz as sv

BASE = Path(__file__).resolve().parent.parent
DATA = BASE / "data" / "indian_retail_sales.csv"
REPORTS = BASE / "reports"
CHARTS = BASE / "charts"
EVIDENCE = BASE / "evidence"

for folder in [REPORTS, CHARTS, EVIDENCE]:
    folder.mkdir(parents=True, exist_ok=True)

df = pd.read_csv(DATA)
df["Sales Date"] = pd.to_datetime(df["Sales Date"])

# Automated summary
summary = df.describe(include="all").transpose()
summary.to_csv(REPORTS / "data_summary.csv")

# Business summaries
df.groupby("Region")[["Sales", "Profit"]].sum().to_csv(
    REPORTS / "regional_performance.csv"
)
df.groupby("Category of Goods")[["Sales", "Profit"]].sum().to_csv(
    REPORTS / "category_performance.csv"
)
df.groupby(df["Sales Date"].dt.to_period("M"))[["Sales", "Profit"]].sum().to_csv(
    REPORTS / "monthly_performance.csv"
)

# Automated visualizations
charts = [
    ("regional_sales.png", df.groupby("Region")["Sales"].sum(), "Sales by Region"),
    ("category_sales.png", df.groupby("Category of Goods")["Sales"].sum(), "Sales by Category"),
    ("regional_profit.png", df.groupby("Region")["Profit"].sum(), "Profit by Region"),
]

for filename, values, title in charts:
    plt.figure(figsize=(10, 5))
    values.sort_values(ascending=False).plot(kind="bar")
    plt.title(title)
    plt.ylabel("Amount")
    plt.tight_layout()
    plt.savefig(CHARTS / filename)
    plt.close()

# Automated business insights
region_sales = df.groupby("Region")["Sales"].sum()
region_profit = df.groupby("Region")["Profit"].sum()
category_sales = df.groupby("Category of Goods")["Sales"].sum()
category_profit = df.groupby("Category of Goods")["Profit"].sum()

insights = [
    f"Highest sales region: {region_sales.idxmax()} (Rs. {region_sales.max():,.2f})",
    f"Highest profit region: {region_profit.idxmax()} (Rs. {region_profit.max():,.2f})",
    f"Highest sales category: {category_sales.idxmax()} (Rs. {category_sales.max():,.2f})",
    f"Highest profit category: {category_profit.idxmax()} (Rs. {category_profit.max():,.2f})",
    f"Total sales: Rs. {df['Sales'].sum():,.2f}",
    f"Total profit: Rs. {df['Profit'].sum():,.2f}",
]

(EVIDENCE / "business_insights.txt").write_text(
    "\n".join(insights), encoding="utf-8"
)

# Dataset quality evidence
quality = [
    f"Rows: {len(df)}",
    f"Columns: {len(df.columns)}",
    f"Missing values: {int(df.isnull().sum().sum())}",
    f"Duplicate rows: {int(df.duplicated().sum())}",
    f"Unique Order IDs: {df['Order ID'].nunique()}",
    f"Unique Customer IDs: {df['Customer ID'].nunique()}",
    f"Sales Date equals Order Date: {(df['Sales Date'].dt.strftime('%Y-%m-%d') == df['Order Date']).sum()}",
    f"Negative profit rows: {(df['Profit'] < 0).sum()}",
    "Note: Automated insights are data-driven; they are not generated by an external LLM."
]
(EVIDENCE / "data_quality.txt").write_text(
    "\n".join(quality), encoding="utf-8"
)

# Sweetviz automated EDA report
report = sv.analyze(df, target_feat="Sales")
report.show_html(
    filepath=str(REPORTS / "sweetviz_eda_report.html"),
    open_browser=False
)

print("SUCCESS: EDA analysis completed.")
print("Rows:", len(df))
print("Charts:", len(charts))
print("Reports and evidence saved.")
